"""
Creates the TPC-H schema in PostgreSQL and bulk-loads the data generated by DuckDB's dbgen.

    python main.py load-data            (scale factor 1, ~8.66 million rows)

Steps: generate CSV (if missing) -> CREATE TABLE -> COPY -> primary keys -> foreign-key
indexes -> VACUUM ANALYZE (planner statistics).
"""

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from qs.config import DATA_DIR
from qs.db import connect

SCHEMA = """
DROP TABLE IF EXISTS lineitem, orders, partsupp, part, supplier, customer, nation, region CASCADE;
CREATE TABLE region   (r_regionkey INT, r_name CHAR(25), r_comment VARCHAR(152));
CREATE TABLE nation   (n_nationkey INT, n_name CHAR(25), n_regionkey INT, n_comment VARCHAR(152));
CREATE TABLE supplier (s_suppkey INT, s_name CHAR(25), s_address VARCHAR(40), s_nationkey INT,
                       s_phone CHAR(15), s_acctbal DECIMAL(15,2), s_comment VARCHAR(101));
CREATE TABLE customer (c_custkey INT, c_name VARCHAR(25), c_address VARCHAR(40), c_nationkey INT,
                       c_phone CHAR(15), c_acctbal DECIMAL(15,2), c_mktsegment CHAR(10), c_comment VARCHAR(117));
CREATE TABLE part     (p_partkey INT, p_name VARCHAR(55), p_mfgr CHAR(25), p_brand CHAR(10), p_type VARCHAR(25),
                       p_size INT, p_container CHAR(10), p_retailprice DECIMAL(15,2), p_comment VARCHAR(23));
CREATE TABLE partsupp (ps_partkey INT, ps_suppkey INT, ps_availqty INT, ps_supplycost DECIMAL(15,2),
                       ps_comment VARCHAR(199));
CREATE TABLE orders   (o_orderkey INT, o_custkey INT, o_orderstatus CHAR(1), o_totalprice DECIMAL(15,2),
                       o_orderdate DATE, o_orderpriority CHAR(15), o_clerk CHAR(15), o_shippriority INT,
                       o_comment VARCHAR(79));
CREATE TABLE lineitem (l_orderkey INT, l_partkey INT, l_suppkey INT, l_linenumber INT, l_quantity DECIMAL(15,2),
                       l_extendedprice DECIMAL(15,2), l_discount DECIMAL(15,2), l_tax DECIMAL(15,2),
                       l_returnflag CHAR(1), l_linestatus CHAR(1), l_shipdate DATE, l_commitdate DATE,
                       l_receiptdate DATE, l_shipinstruct CHAR(25), l_shipmode CHAR(10), l_comment VARCHAR(44));
"""

KEYS = [
    "ALTER TABLE region   ADD PRIMARY KEY (r_regionkey)",
    "ALTER TABLE nation   ADD PRIMARY KEY (n_nationkey)",
    "ALTER TABLE supplier ADD PRIMARY KEY (s_suppkey)",
    "ALTER TABLE customer ADD PRIMARY KEY (c_custkey)",
    "ALTER TABLE part     ADD PRIMARY KEY (p_partkey)",
    "ALTER TABLE partsupp ADD PRIMARY KEY (ps_partkey, ps_suppkey)",
    "ALTER TABLE orders   ADD PRIMARY KEY (o_orderkey)",
    "ALTER TABLE lineitem ADD PRIMARY KEY (l_orderkey, l_linenumber)",
    # foreign-key columns, as in common TPC-H setups for PostgreSQL
    "CREATE INDEX ON nation (n_regionkey)",
    "CREATE INDEX ON supplier (s_nationkey)",
    "CREATE INDEX ON customer (c_nationkey)",
    "CREATE INDEX ON partsupp (ps_suppkey)",
    "CREATE INDEX ON orders (o_custkey)",
    "CREATE INDEX ON orders (o_orderdate)",
    "CREATE INDEX ON lineitem (l_partkey, l_suppkey)",
    "CREATE INDEX ON lineitem (l_suppkey)",
    "CREATE INDEX ON lineitem (l_shipdate)",
]

TABLES = ["region", "nation", "supplier", "customer", "part", "partsupp", "orders", "lineitem"]


def generate_csv(sf: int, out: Path):
    import duckdb
    out.mkdir(parents=True, exist_ok=True)
    con = duckdb.connect()
    con.execute("INSTALL tpch")
    con.execute("LOAD tpch")
    con.execute(f"CALL dbgen(sf={sf})")
    for t in TABLES:
        con.execute(f"COPY {t} TO '{(out / (t + '.csv')).as_posix()}' (HEADER false, DELIMITER '|')")


def load(sf: int = 1):
    csv_dir = DATA_DIR / f"sf{sf}"
    if not all((csv_dir / f"{t}.csv").exists() for t in TABLES):
        print(f"[load] generating TPC-H SF{sf} with DuckDB dbgen ...")
        generate_csv(sf, csv_dir)
    conn = connect()
    cur = conn.cursor()
    t0 = time.time()
    cur.execute(SCHEMA)
    for t in TABLES:
        t1 = time.time()
        with open(csv_dir / f"{t}.csv", "r", encoding="utf-8") as f:
            cur.copy_expert(f"COPY {t} FROM STDIN WITH (FORMAT csv, DELIMITER '|')", f)
        cur.execute(f"SELECT count(*) FROM {t}")
        print(f"[load] {t:9s} {cur.fetchone()[0]:>10,d} rows  ({time.time() - t1:5.1f} s)", flush=True)
    for stmt in KEYS:
        t1 = time.time()
        cur.execute(stmt)
        print(f"[load] {stmt[:62]:62s} ({time.time() - t1:5.1f} s)", flush=True)
    cur.execute("VACUUM ANALYZE")
    print(f"[load] done in {time.time() - t0:.0f} s")


if __name__ == "__main__":
    load(int(sys.argv[1]) if len(sys.argv) > 1 else 1)
